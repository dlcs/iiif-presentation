using Core.Helpers;
using Core.IIIF;
using IIIF;
using IIIF.Presentation.V3;
using IIIF.Presentation.V3.Strings;
using IIIF.Search.V2;
using Microsoft.Extensions.Logging;
using Services.Manifests;
using DbManifest = Models.Database.Collections.Manifest;

namespace Services.TextServices;

/// <summary>
/// Augments a manifest with text-services content - retrieving the text-augmented manifest from text-services and
/// merging any <see cref="SearchService2"/>, rendering (e.g. manifest-level PDF and per-canvas SVG text layer) and
/// annotations (e.g. manifest-level "all-text" and per-canvas line/word transcriptions from METS/ALTO) into the
/// manifest.
/// </summary>
public interface ITextManifestAugmentor : IManifestAugmentor
{
}

public class TextManifestAugmentor(
    ITextSearchClient textSearchClient,
    ITextServiceIdRewriter idRewriter,
    ILogger<TextManifestAugmentor> logger)
    : ITextManifestAugmentor
{
    public async Task<Manifest> Augment(Manifest manifest, DbManifest dbManifest, CancellationToken cancellationToken)
    {
        // The job id is deterministic from the manifest - see PipelineJobX.GetJobId
        var jobId = new TextJobId(dbManifest.CustomerId, dbManifest.Id);

        var augmented = await textSearchClient.GetTextAugmentedManifest(jobId, cancellationToken);
        if (augmented == null) return manifest;

        // Rewrite ids onto the correct orchestrator host/path before merging - AddDistinctById below dedupes
        // by exact id match, so this has to happen first for it to correctly recognise a customer-supplied
        // service/rendering/annotation that already uses the correct (rewritten) id.
        idRewriter.Rewrite(augmented, dbManifest, jobId);

        AddSearchServices(manifest, augmented, jobId);
        AddRendering(manifest, augmented, jobId);
        AddManifestAnnotations(manifest, augmented, jobId);
        AddCanvasContent(manifest, augmented, jobId);

        return manifest;
    }

    private void AddSearchServices(Manifest manifest, Manifest augmented, TextJobId jobId)
    {
        var searchServices = augmented.Service?.OfType<SearchService2>().ToList();
        if (searchServices.IsNullOrEmpty())
        {
            logger.LogDebug("No SearchService2 in text-augmented manifest for job {JobId}", jobId);
            return;
        }

        // Add search service to manifest, if added then ensure Manifest has the search context
        manifest.Service ??= [];
        var added = manifest.Service.AddDistinctById(searchServices, AddService);
        if (added > 0)
        {
            manifest.EnsureContext(SearchService2.Search2Context);
            logger.LogDebug("Added SearchService2 to manifest for job {JobId}", jobId);
        }
        else
        {
            logger.LogDebug("Found SearchService2 but did not augment manifest for job {JobId}", jobId);
        }
    }

    /// <summary>
    /// Add any PDF renderings generated by text-services (e.g. a searchable PDF) to the manifest.
    /// </summary>
    private void AddRendering(Manifest manifest, Manifest augmented, TextJobId jobId)
    {
        if (augmented.Rendering.IsNullOrEmpty())
        {
            logger.LogDebug("No rendering in text-augmented manifest for job {JobId}", jobId);
            return;
        }

        manifest.Rendering ??= [];
        var added = manifest.Rendering.AddDistinctById(augmented.Rendering);
        logger.LogDebug("Added {Count} rendering to manifest for job {JobId}", added, jobId);
    }

    /// <summary>
    /// Add any manifest-level W3C annotations generated by text-services (e.g. the "all-text" page, figures) to
    /// the manifest.
    /// </summary>
    private void AddManifestAnnotations(Manifest manifest, Manifest augmented, TextJobId jobId)
    {
        if (augmented.Annotations.IsNullOrEmpty())
        {
            logger.LogDebug("No manifest-level annotations in text-augmented manifest for job {JobId}", jobId);
            return;
        }

        manifest.Annotations ??= [];
        var added = manifest.Annotations.AddDistinctById(augmented.Annotations);
        logger.LogDebug("Added {Count} manifest-level annotations to manifest for job {JobId}", added, jobId);
    }

    /// <summary>
    /// Add any canvas-level rendering (e.g. SVG text layer) and W3C annotations (e.g. line/word transcriptions from
    /// METS/ALTO) generated by text-services to the matching canvas, matched by canvas id.
    /// </summary>
    private void AddCanvasContent(Manifest manifest, Manifest augmented, TextJobId jobId)
    {
        if (manifest.Items.IsNullOrEmpty() || augmented.Items.IsNullOrEmpty())
        {
            logger.LogDebug("No canvases to add canvas-level content to for job {JobId}", jobId);
            return;
        }

        // GroupBy avoids issues with duplicate canvas id's
        var augmentedCanvasesById = augmented.Items
            .Where(c => c.Id != null)
            .GroupBy(c => c.Id!)
            .ToDictionary(g => g.Key, g => g.First());

        var renderingUpdated = 0;
        var annotationsUpdated = 0;
        foreach (var canvas in manifest.Items)
        {
            if (canvas.Id == null || !augmentedCanvasesById.TryGetValue(canvas.Id, out var augmentedCanvas))
                continue;

            if (!augmentedCanvas.Rendering.IsNullOrEmpty())
            {
                canvas.Rendering ??= [];
                if (canvas.Rendering.AddDistinctById(augmentedCanvas.Rendering) > 0) renderingUpdated++;
            }

            if (!augmentedCanvas.Annotations.IsNullOrEmpty())
            {
                canvas.Annotations ??= [];
                if (canvas.Annotations.AddDistinctById(augmentedCanvas.Annotations) > 0) annotationsUpdated++;
            }
        }

        logger.LogDebug(
            "Added canvas-level rendering to {RenderingCount} and annotations to {AnnotationsCount} canvases for " +
            "job {JobId}", renderingUpdated, annotationsUpdated, jobId);
    }

    private static void AddService(IService service)
    {
        // Expectation is we'll get a SearchService2 containing an AutoCompleteService2. Set labels on these if null
        if (service is SearchService2 searchService)
        {
            searchService.Label ??= new LanguageMap("en", "Search within this manifest");
            // We're only expecting 1 here but use FirstOrDefault, rather than SingleOrDefault to avoid throwing if
            // text-service adds unexpected service.
            var autoComplete = searchService.Service?.OfType<AutoCompleteService2>().FirstOrDefault();
            if (autoComplete != null)
            {
                autoComplete.Label ??= new LanguageMap("en", "Autocomplete words in this manifest");
            }
        }
    }
}
